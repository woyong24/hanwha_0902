import numpy as np

# 2차원 NumPy 배열 생성
arr = np.array([
    [1, 2, 3],
    [4, 5, 6]
])

# 배열의 모든 요소에 10을 더함
# NumPy는 반복문 없이 전체 요소에 한 번에 연산 가능
print("10 더하기:\n", arr + 10)

# 배열의 모든 요소에 2를 곱함
print("2 곱하기:\n", arr * 2)

# 배열 전체 요소의 합계
print("전체 합계:", arr.sum())

# 열별 평균 계산
# axis=0 → 세로 방향으로 계산
print("열별 평균(axis=0):", arr.mean(axis=0))

# 행별 최댓값 계산
# axis=1 → 가로 방향으로 계산
print("행별 최댓값(axis=1):", arr.max(axis=1))


# 결과
# 10 더하기:
# [[11 12 13]
#  [14 15 16]]

# 2 곱하기:
# [[ 2  4  6]
#  [ 8 10 12]]

# 전체 합계: 21
# 열별 평균(axis=0): [2.5 3.5 4.5]
# 행별 최댓값(axis=1): [3 6]